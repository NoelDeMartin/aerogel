import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';

import { arraySorted } from '@noeldemartin/utils';

const MODELS_DECLARATION_PATH = 'src/types/models.d.ts';

function isModelFile(fileName: string): boolean {
    return (
        fileName.endsWith('.ts') &&
        fileName !== 'index.ts' &&
        !fileName.endsWith('.schema.ts') &&
        !fileName.endsWith('.test.ts') &&
        !fileName.endsWith('.d.ts')
    );
}

function findModelsDirectories(root: string): string[] {
    const directories = [resolve(root, 'src/models')];
    const modulesDirectory = resolve(root, 'src/modules');

    if (existsSync(modulesDirectory)) {
        for (const entry of readdirSync(modulesDirectory, { withFileTypes: true })) {
            if (!entry.isDirectory()) {
                continue;
            }

            directories.push(resolve(modulesDirectory, entry.name, 'models'));
        }
    }

    return directories.filter((directory) => existsSync(directory));
}

function hasDefaultExportValue(path: string): boolean {
    const source = readFileSync(path).toString();

    return /export\s+default\s+/.test(source) && !/export\s+default\s+(interface|type)\s/.test(source);
}

export function isModelPath(root: string, path: string): boolean {
    const relativePath = relative(root, path).replaceAll('\\', '/');

    return (
        /^src\/(modules\/[^/]+\/)?models\/[^/]+$/.test(relativePath) && isModelFile(relativePath.split('/').pop() ?? '')
    );
}

export function findModels(root: string): Record<string, string> {
    const models: Record<string, string> = {};

    for (const directory of findModelsDirectories(root)) {
        for (const fileName of readdirSync(directory)) {
            if (!isModelFile(fileName) || !hasDefaultExportValue(resolve(directory, fileName))) {
                continue;
            }

            const name = fileName.slice(0, -'.ts'.length);

            if (name in models) {
                throw new Error(
                    `Found duplicated model "${name}" in ${relative(root, models[name] as string)} ` +
                        `and ${relative(root, resolve(directory, fileName))}.`,
                );
            }

            models[name] = resolve(directory, fileName);
        }
    }

    return models;
}

export function generateModelsDeclaration(root: string): void {
    const models = findModels(root);
    const declarationPath = resolve(root, MODELS_DECLARATION_PATH);

    if (Object.keys(models).length === 0) {
        rmSync(declarationPath, { force: true });

        return;
    }

    const registryEntries = arraySorted(Object.keys(models)).map((name) => {
        const relativePath = relative(dirname(declarationPath), models[name] as string)
            .replaceAll('\\', '/')
            .replace(/\.ts$/, '');
        const importPath = relativePath.startsWith('.') ? relativePath : `./${relativePath}`;

        return `        ${name}: typeof import('${importPath}')['default']`;
    });
    const declaration = [
        '/* eslint-disable */',
        '// @ts-nocheck',
        '// Generated by @aerogel/vite',
        'export {}',
        '',
        "declare module 'soukai-bis' {",
        '    export interface ModelsRegistry {',
        ...registryEntries,
        '    }',
        '}',
        '',
    ].join('\n');

    if (existsSync(declarationPath) && readFileSync(declarationPath).toString() === declaration) {
        return;
    }

    mkdirSync(dirname(declarationPath), { recursive: true });
    writeFileSync(declarationPath, declaration);
}

export function generateModelsVirtualModule(): string {
    const patterns = [
        '/src/models/*.ts',
        '/src/modules/*/models/*.ts',
        '!/src/**/models/*.test.ts',
        '!/src/**/models/index.ts',
    ];

    return `export default import.meta.glob(${JSON.stringify(patterns)}, { eager: true });`;
}

export function generateModelsWorkerVirtualModule(): string {
    return "export { default } from '@aerogel/plugin-solid/models-worker?worker';";
}

export function generatePatchZodVirtualModule(): string {
    return "import 'soukai-bis/patch-zod';";
}
